            "# Asymmetric Loss (ASL) implementation with confidence weighting\n",
            "def asymmetric_loss(\n",
            "    pred: torch.Tensor,\n",
            "    target: torch.Tensor,\n",
            "    weights: Optional[torch.Tensor] = None,\n",
            "    gamma_neg: float = 4.0,\n",
            "    gamma_pos: float = 0.0,\n",
            "    clip: float = 0.05,\n",
            ") -> torch.Tensor:\n",
            "    xs_pos = pred.clamp(min=1e-8, max=1.0)\n",
            "    xs_neg = (1.0 - pred + clip).clamp(min=1e-8, max=1.0)\n",
            "    los_pos = target * torch.log(xs_pos)\n",
            "    los_neg = (1.0 - target) * torch.log(xs_neg)\n",
            "    neg_weight = (1.0 - xs_neg) ** gamma_neg\n",
            "    los_neg = neg_weight * los_neg\n",
            "    loss = -(los_pos + los_neg)\n",
            "    if weights is not None:\n",
            "        loss = loss * weights\n",
            "        return loss.sum() / (weights.sum() + 1e-8)\n",
            "    return loss.mean()\n",
