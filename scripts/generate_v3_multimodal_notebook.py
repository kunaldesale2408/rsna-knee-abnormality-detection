            "        except Exception as e:\n",
            "            print(f'[-] HF load warning: {e}. Using StandaloneTextEncoder.')\n",
            "\n",
            "        if not self.is_hf:\n",
            "            self.hidden_dim = 768\n",
            "            self.fallback_encoder = StandaloneTextEncoder(embed_dim=self.hidden_dim)\n",
            "\n",
            "        self.projector = nn.Sequential(\n",
            "            nn.Linear(self.hidden_dim, proj_dim),\n",
            "            nn.ReLU(inplace=True),\n",
            "            nn.Dropout(0.2),\n",
            "        )\n",
            "        self.text_head = nn.Linear(proj_dim, num_classes)\n",
            "\n",
