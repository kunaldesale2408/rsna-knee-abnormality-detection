            "            x = (x * mask).sum(dim=1) / (mask.sum(dim=1).clamp(min=1e-8))\n",
            "        else:\n",
            "            x = x.mean(dim=1)\n",
            "        return x\n",
            "\n",
            "class TextBranchWrapper(nn.Module):\n",
            "    def __init__(self, model_name: str, proj_dim: int = 256, num_classes: int = 12):\n",
            "        super().__init__()\n",
            "        self.model_name = model_name\n",
            "        self.proj_dim = proj_dim\n",
            "        self.num_classes = num_classes\n",
            "        self.hf_model = None\n",
            "        self.is_hf = False\n",
            "\n",
            "        try:\n",
            "            from transformers import AutoModel, AutoTokenizer\n",
            "            # Search paths\n",
            "            cands = [\n",
            "                resolve_weights(model_name.split('/')[-1]),\n",
            "                resolve_weights('biomedbert'),\n",
            "                resolve_weights('me5'),\n",
            "                resolve_weights('mdeberta'),\n",
