            "        enc = self.hf_model if self.is_hf else self.fallback_encoder\n",
            "        for p in enc.parameters():\n",
            "            p.requires_grad = not frozen\n",
            "\n",
            "    def forward(self, input_ids: torch.Tensor, attention_mask: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:\n",
            "        if self.is_hf and self.hf_model is not None:\n",
            "            out = self.hf_model(input_ids=input_ids, attention_mask=attention_mask)\n",
            "            if hasattr(out, 'hidden_states') and out.hidden_states is not None:\n",
            "                # Mean pool last 4 hidden layers\n",
            "                last_4 = out.hidden_states[-4:]\n",
            "                stacked = torch.stack(last_4, dim=0).mean(dim=0) # [B, L, hidden_dim]\n",
            "            else:\n",
            "                stacked = out.last_hidden_state\n",
            "            mask = attention_mask.unsqueeze(-1).float()\n",
            "            pooled = (stacked * mask).sum(dim=1) / (mask.sum(dim=1).clamp(min=1e-8))\n",
            "        else:\n",
            "            pooled = self.fallback_encoder(input_ids, attention_mask)\n",
            "\n",
            "        proj = self.projector(pooled) # [B, proj_dim]\n",
            "        logits = self.text_head(proj)  # [B, 12]\n",
            "        return logits, proj\n",
